-- ----------------------------------------------------------------------------
--  project — the project master.
--
--  ★ THE SOURCE FILE'S LONG NOTE ON `level_code` APPLIES HERE UNCHANGED, and the
--    translation must not lose it: a project exists as a NAME before anybody has
--    decided which account level funds it, so `level_code` is NULLABLE. It is
--    also UNIQUE, and SQLite permits many NULLs in a UNIQUE column -- which is
--    what makes "not yet associated" storable more than once.
--
--  ★★ T-SQL DOES NOT PERMIT MANY NULLS IN A UNIQUE CONSTRAINT, AND THIS IS THE
--     ONE PLACE THE TWO DATABASES GENUINELY DIFFER. SQL Server treats NULL as a
--     value for uniqueness, so a plain `UNIQUE` would allow only ONE unassigned
--     project. A filtered unique index is the T-SQL equivalent:
--
--         CREATE UNIQUE INDEX ... WHERE level_code IS NOT NULL
--
--     which enforces "two projects cannot claim the same level" while leaving
--     any number of unassigned projects storable. Without the filter, the second
--     unassigned project would be refused and the app would appear to lose a row.
-- ----------------------------------------------------------------------------
IF OBJECT_ID('dbo.project', 'U') IS NULL
CREATE TABLE dbo.project (
  id          INT IDENTITY(1,1) NOT NULL PRIMARY KEY,

  slug        NVARCHAR(200) NOT NULL UNIQUE,

  name        NVARCHAR(400) NOT NULL,
  description NVARCHAR(MAX) NULL,

  -- The SEGMENT5 value this project claims, or NULL when nobody has said yet.
  -- NO inline UNIQUE here -- see the filtered index below, which is the T-SQL
  -- form of "unique, but many NULLs allowed".
  level_code  NVARCHAR(20) NULL,

  code        NVARCHAR(50) NULL,
  site        NVARCHAR(200) NULL,
  owner       NVARCHAR(200) NULL,

  created_at  NVARCHAR(30) NOT NULL DEFAULT (CONVERT(varchar(19), GETUTCDATE(), 126)),
  updated_at  NVARCHAR(30) NOT NULL DEFAULT (CONVERT(varchar(19), GETUTCDATE(), 126))
);
GO

-- ★ THE FILTERED INDEX IS THE POINT. `WHERE level_code IS NOT NULL` is what makes
--   this behave like SQLite's UNIQUE-with-many-NULLs rather than SQL Server's
--   UNIQUE-with-one-NULL.
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UQ_project_level_code' AND object_id = OBJECT_ID('dbo.project'))
  CREATE UNIQUE INDEX UQ_project_level_code ON dbo.project (level_code) WHERE level_code IS NOT NULL;
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IDX_PROJECT_NAME' AND object_id = OBJECT_ID('dbo.project'))
  CREATE INDEX IDX_PROJECT_NAME ON dbo.project (name);
GO


-- ----------------------------------------------------------------------------
--  organization — the tenant.
-- ----------------------------------------------------------------------------
IF OBJECT_ID('dbo.organization', 'U') IS NULL
CREATE TABLE dbo.organization (
  id             INT IDENTITY(1,1) NOT NULL PRIMARY KEY,

  slug           NVARCHAR(200) NOT NULL UNIQUE,
  name           NVARCHAR(400) NOT NULL,

  -- The Fund segment value as the chart of accounts spells it -- '04', not 4.
  -- Leading zeros are significant in every segment of this account structure,
  -- which is why it is NVARCHAR and not INT.
  fund           NVARCHAR(10) NOT NULL,

  programs_json  NVARCHAR(MAX) NOT NULL DEFAULT '[]',

  start_fy       INT NOT NULL,

  is_default     BIT NOT NULL DEFAULT 0,

  created_at     NVARCHAR(30) NOT NULL DEFAULT (CONVERT(varchar(19), GETUTCDATE(), 126)),
  updated_at     NVARCHAR(30) NOT NULL DEFAULT (CONVERT(varchar(19), GETUTCDATE(), 126))
);
GO

-- ★ THE RULE, NOT A CONVENTION: at most one row may claim is_default. The source
--   file uses SQLite's partial index for this (`WHERE is_default = 1`); the same
--   filtered-index form works in T-SQL, and the filter is what makes it a rule
--   rather than "at most one 0 and at most one 1".
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'organization_one_default' AND object_id = OBJECT_ID('dbo.organization'))
  CREATE UNIQUE INDEX organization_one_default ON dbo.organization (is_default) WHERE is_default = 1;
GO


-- ----------------------------------------------------------------------------
--  app_user — who may sign in, and which tenant they see.
--
--  ★ NO PASSWORD COLUMN, DELIBERATELY. See the source file: a column named
--    `password_hash` holding nothing would be worse than its absence, because a
--    reader would assume it was the real thing.
--
--  ★ `organization_id` IS NULLABLE EVEN THOUGH EVERY USER BELONGS TO ONE.
--    "Belongs to an organization" and "has been given one here yet" are different
--    states, and collapsing them would make an unassigned user silently inherit
--    the default. A NULL means "not assigned" and the sign-in path refuses.
-- ----------------------------------------------------------------------------
IF OBJECT_ID('dbo.app_user', 'U') IS NULL
CREATE TABLE dbo.app_user (
  id              INT IDENTITY(1,1) NOT NULL PRIMARY KEY,

  -- Lower-cased on write; the lookup lower-cases what it was given, so
  -- `Dana@x.gov` and `dana@x.gov` are one account and not two.
  email           NVARCHAR(320) NOT NULL UNIQUE,

  display_name    NVARCHAR(200) NOT NULL,

  role            NVARCHAR(20) NOT NULL DEFAULT 'member'
                    CONSTRAINT CK_app_user_role CHECK (role IN ('super_admin','member')),

  organization_id INT NULL,

  created_at      NVARCHAR(30) NOT NULL DEFAULT (CONVERT(varchar(19), GETUTCDATE(), 126)),

  -- NULL means the account has never been used, which is a different fact from
  -- "used a long time ago".
  last_seen_at    NVARCHAR(30) NULL,

  CONSTRAINT FK_app_user_org FOREIGN KEY (organization_id) REFERENCES dbo.organization (id)
);
GO


