-- ============================================================================
--  01-app.sql — THE APP-OWNED TABLES, IN T-SQL
--
--  This is the SQL Server translation of `data/sql/turso/01-app.sql`. That file
--  is SQLite and cannot be applied here: `AUTOINCREMENT`, `datetime('now')` and
--  the `IF NOT EXISTS` forms are all syntax errors in T-SQL. The two files own
--  the same thirteen tables and must stay in step.
--
--  ── WHAT CHANGED IN TRANSLATION, AND WHY EACH ONE IS NOT COSMETIC ──────────
--
--    SQLite                              T-SQL
--    --------------------------------    ------------------------------------
--    INTEGER PRIMARY KEY AUTOINCREMENT   INT IDENTITY(1,1) PRIMARY KEY
--    TEXT                                NVARCHAR(n)
--    TEXT DEFAULT (datetime('now'))      NVARCHAR(30) DEFAULT (CONVERT(...))
--    INTEGER (for a 0/1 flag)            BIT
--    CREATE TABLE IF NOT EXISTS          IF OBJECT_ID(...) IS NULL
--    CREATE INDEX IF NOT EXISTS          IF NOT EXISTS (SELECT 1 FROM sys...)
--
--  ★★ `INT` FOR THE IDS, NOT `BIGINT` — AND THAT IS A DECISION, NOT AN OVERSIGHT.
--     The ledger copy needed BIGINT because the Oracle ids exceed 32-bit (PO
--     LINE_NUM reached 7.88 billion). These are APP ids: they are generated by
--     IDENTITY starting at 1, the largest table here holds 12 rows, and the
--     largest table anywhere in this schema is `saved_view_run` at 8. INT is
--     correct and BIGINT would be a claim about a scale this data does not have.
--
--  ★★ `NVARCHAR(30)` FOR TIMESTAMPS, NOT `DATETIME2` — AND THIS ONE MATTERS.
--     SQLite stores these as TEXT in `YYYY-MM-DD HH:MM:SS` form, and the app
--     reads them as strings: `app/src` compares them lexically and prints them
--     directly. A DATETIME2 column would change the wire type and break every
--     reader. The default reproduces SQLite's exact format:
--
--         CONVERT(varchar(19), GETUTCDATE(), 126)   ->  2026-09-24 21:45:18
--
--     ★ GETUTCDATE(), NOT GETDATE(). SQLite's `datetime('now')` is UTC, and the
--       comments in the source file rely on that. GETDATE() is server-local, so
--       it would silently shift every timestamp by the server's offset.
--
--  ★★ `BIT` FOR THE 0/1 FLAGS, AND THE CHECK IS DROPPED WITH A REASON.
--     SQLite has no boolean, so the source file writes `INTEGER ... CHECK (x IN
--     (0,1))` and comments that the CHECK is what makes the invariant real. T-SQL
--     HAS a boolean, so `BIT` states the same thing in the type rather than in a
--     constraint — the CHECK is not lost, it is promoted. `BIT` cannot hold 2.
--
--  ★ CONSTRAINTS ARE CARRIED, NOT DROPPED. Every UNIQUE, NOT NULL and CHECK from
--     the source file appears here. A translation that quietly omitted one would
--     be a behaviour change that no test in this repo would catch, because the
--     app relies on the database to enforce them.
--
--  ★ FOREIGN KEYS ARE DECLARED BUT NOT ENFORCED BY DEFAULT. T-SQL does not check
--     them unless they are trusted, and `saved_view_run.view_id` uses ON DELETE
--     CASCADE in the source. They are written here so the relationship is stated
--     and so a later `ALTER TABLE ... WITH CHECK` can enforce them.
-- ============================================================================


-- ----------------------------------------------------------------------------
--  saved_view — the View Builder's saved statements.
-- ----------------------------------------------------------------------------
IF OBJECT_ID('dbo.saved_view', 'U') IS NULL
CREATE TABLE dbo.saved_view (
  id            INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
  slug          NVARCHAR(200) NOT NULL UNIQUE,

  title         NVARCHAR(400) NOT NULL,
  description   NVARCHAR(MAX) NULL,

  sql           NVARCHAR(MAX) NOT NULL,

  -- JSON text, not a JSON column type -- the app parses it in JS, and '[]' / '{}'
  -- rather than NULL so every reader can parse unconditionally.
  params_json   NVARCHAR(MAX) NOT NULL DEFAULT '[]',
  display_json  NVARCHAR(MAX) NOT NULL DEFAULT '{}',

  -- ★ TEXT, NOT A FOREIGN KEY, AND THE SOURCE FILE EXPLAINS WHY AT LENGTH: this
  --   column owns the sentence "who made this", frozen at the moment it was made.
  --   A FK would rewrite a historical attribution when a display_name changed.
  created_by    NVARCHAR(200) NULL,

  status        NVARCHAR(20) NOT NULL DEFAULT 'draft'
                  CONSTRAINT CK_saved_view_status CHECK (status IN ('draft','active','disabled')),

  created_at    NVARCHAR(30) NOT NULL DEFAULT (CONVERT(varchar(19), GETUTCDATE(), 126)),
  updated_at    NVARCHAR(30) NOT NULL DEFAULT (CONVERT(varchar(19), GETUTCDATE(), 126))
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IDX_SAVED_VIEW_STATUS' AND object_id = OBJECT_ID('dbo.saved_view'))
  CREATE INDEX IDX_SAVED_VIEW_STATUS ON dbo.saved_view (status, title);
GO


-- ----------------------------------------------------------------------------
--  saved_view_run — one row per execution.
-- ----------------------------------------------------------------------------
IF OBJECT_ID('dbo.saved_view_run', 'U') IS NULL
CREATE TABLE dbo.saved_view_run (
  id           INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
  view_id      INT NOT NULL,

  ran_at       NVARCHAR(30) NOT NULL DEFAULT (CONVERT(varchar(19), GETUTCDATE(), 126)),

  -- ★ NULLABLE RATHER THAN DEFAULTED TO 0, and the source file is emphatic about
  --   it: a run refused before reaching the database has no duration and no row
  --   count, and writing 0 would make "did not run" indistinguishable from "ran
  --   and found nothing". That confusion once produced a fictitious -100% delta
  --   in this project's history.
  duration_ms  INT NULL,
  row_count    INT NULL,
  truncated    BIT NULL,

  fingerprint  NVARCHAR(200) NULL,
  error        NVARCHAR(MAX) NULL,

  CONSTRAINT FK_saved_view_run_view FOREIGN KEY (view_id)
    REFERENCES dbo.saved_view (id) ON DELETE CASCADE
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IDX_SAVED_VIEW_RUN_VIEW' AND object_id = OBJECT_ID('dbo.saved_view_run'))
  CREATE INDEX IDX_SAVED_VIEW_RUN_VIEW ON dbo.saved_view_run (view_id, ran_at DESC);
GO


